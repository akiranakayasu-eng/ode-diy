def rot270(items, f):
    """sacn_node_main の配置を 270 度回す。表の部品は rot + 270、裏の部品は (Flip で向きが反転するので) rot + 90"""
    out = {}
    for ref, v in items.items():
        x, y, rot = v[:3]
        side = v[3] if len(v) > 3 else "F"
        nx, ny = f(x, y)
        nr = (rot + (90 if side == "B" else 270)) % 360
        out[ref] = (round(nx, 4), round(ny, 4), nr) + ((side,) if side == "B" else ())
    return out


